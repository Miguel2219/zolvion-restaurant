def now() -> str:
    """Microseconds, not seconds. Two messages can land in the same second, and
    the worker answers a phone's messages in the order they arrived. Still sorts
    correctly as a string against a seconds-precision bound."""
    return datetime.now(timezone.utc).isoformat(timespec="microseconds")


def describe() -> str:
    """host:port/database, never the password. For the startup banner."""
    parts = conninfo_to_dict(DATABASE_URL)
    return f"{parts.get('host', 'localhost')}:{parts.get('port', 5432)}/{parts.get('dbname', '')}"


def conn() -> psycopg.Connection:
    """One connection per thread, in autocommit: a statement outside transaction()
    commits on its own, so no connection sits idle inside an open transaction."""
    connection = getattr(_local, "conn", None)
    if connection is None or connection.closed:
        connection = psycopg.connect(DATABASE_URL, autocommit=True, row_factory=dict_row)
        _local.conn = connection
    return connection


def init() -> None:
    try:
        conn().execute(SCHEMA)
        conn().execute(UPGRADE)
    except psycopg.OperationalError as exc:
        raise RuntimeError(
            f"No hay conexión con PostgreSQL en {describe()}. "
            "¿Está corriendo `docker compose up -d`? Revise DATABASE_URL en .env."
        ) from exc


def reset() -> None:
    """Wipe everything. Used before a demo run so reports start clean. DELETE, not
    TRUNCATE: on these few rows it is about 25 times faster, and every test runs it."""
    with transaction():
        for table in TABLES:
            run(f"DELETE FROM {table}")


# ---- small helpers --------------------------------------------------

def q(sql: str, args=None) -> list[dict]:
    return conn().execute(sql, args).fetchall()


def q1(sql: str, args=None) -> dict | None:
    return conn().execute(sql, args).fetchone()


def run(sql: str, args=None) -> psycopg.Cursor:
    """Outside transaction() the statement commits on its own, and a rejected one
    (the UNIQUE constraints are load-bearing here) leaves nothing behind. Inside
    transaction() a failure aborts the whole block."""
    return conn().execute(sql, args)


def insert(sql: str, args=None) -> int:
    """An INSERT ... RETURNING id: the new row's id."""
    return run(sql, args).fetchone()["id"]


@contextmanager
def transaction():
    """Several writes that land together or not at all. The block commits once at
    the end, or rolls back on any exception - so a failure half-way leaves nothing
    behind. Code inside must not catch a failed run() and carry on: PostgreSQL has
    aborted the transaction by then, and every later statement in it fails."""
    if getattr(_local, "in_tx", False):     # already inside one: join it
        yield
        return
    _local.in_tx = True
    try:
        with conn().transaction():
            yield
    finally:
        _local.in_tx = False


def jloads(value, default):
    try:
        return json.loads(value) if value else default
    except (TypeError, ValueError):
        return default
